def build_iso19115_metadata_catalog() -> dict[str, Any]:
    """Return an ISO 19115 / DCAT-AP / OGC API - Records compliant catalog across twin + panel layers."""
    panel_records = [
        _rec(
            identifier=layer_id,
            title=layer_id.replace("_", " ").title(),
            abstract=f"Capa territorial publicada en panel.bcs2050.com ({meta['data_nature']}).",
            source_agency=meta["source_agency"],
            source_url=meta["source_url"],
            reference_date=meta["reference_date"],
            update_cadence=meta["update_cadence"],
            crs=meta["crs"],
            spatial_accuracy_note=meta["spatial_accuracy_note"],
            data_nature=meta["data_nature"],
            license_spdx=meta["license_spdx"],
            attribution_text=meta["attribution_text"],
            distribution_url=f"https://bcs2050-territorial-ia-96586614897.northamerica-south1.run.app/api/layers/{layer_id}",
            dataset_scope="panel_v2_release",
        )
        for layer_id, meta in PANEL_V2_ISO19115_BY_ID.items()
    ]

    all_records = [*TWIN_LOCAL_DATASET_RECORDS, *panel_records]
    by_nature: dict[str, int] = {}
    for r in all_records:
        by_nature[r["data_nature"]] = by_nature.get(r["data_nature"], 0) + 1

    return {
        "standard": "ISO 19115 / DCAT-AP / OGC API - Records",
        "conformsTo": [
            "http://www.opengis.net/spec/ogcapi-records-1/1.0/conf/core",
            "https://www.iso.org/standard/53798.html",
            "https://spdx.org/licenses/",
        ],
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "basemap_attributions": [
            "Esri World Dark Gray Base & World Imagery (requiere atribución Esri, Maxar, Earthstar Geographics en aplicaciones públicas).",
            "Google Research OpenBuildings 2.5D (CC-BY-4.0).",
            "Copernicus Digital Elevation Model GLO-30 (Copernicus Data & Information Access).",
        ],
        "summary": {
            "total_records": len(all_records),
            "twin_records": len(TWIN_LOCAL_DATASET_RECORDS),
            "panel_v2_records": len(panel_records),
            "counts_by_data_nature": by_nature,
        },
        "canonical_kpis": CANONICAL_KPI_RECONCILIATION,
        "records": all_records,
    }
